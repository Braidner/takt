/**
 * Ответ команды агенту.
 *
 * Три вещи, которые команда обязана сказать, и одно место, где это решается:
 *
 *   1. Что получилось — данными, в TOON: тот же JSON, но без скобок и без повтора
 *      имён полей в каждой записи. У раскадровки из сорока планов имя `seconds`
 *      печаталось сорок раз; теперь один раз заголовком таблицы.
 *   2. Что делать дальше — строками `help[]` с готовой командой, а не намёком.
 *      Пока подсказок не было, порядок конвейера жил в справочниках, то есть в
 *      документе, который может врать: в ревизии их набралось девять ложных
 *      утверждений, и заметил их не агент, а человек на готовом ролике.
 *   3. Чем кончилось — кодом возврата. Ноль — сделано, единица — работа не
 *      удалась, двойка — команду позвали неправильно. Разделять их важно:
 *      на единицу агент повторяет с другими данными, на двойку — читает `--help`.
 */
import { encode as toon } from '@toon-format/toon';

export const КОД = { ok: 0, fail: 1, usage: 2 };

/**
 * Поля без значения выбрасываются, а не превращаются в null.
 *
 * Библиотека кодирует `undefined` как `null`, и в ответе появляются строки вида
 * `fix: null` — про поля, которых у этой записи нет вовсе. Для агента это разные
 * вещи: «плану нечего чинить» и «плана чинить не пробовали». Первое он прочитает
 * как факт и не станет спрашивать.
 */
function чисто(v) {
  if (Array.isArray(v)) return v.map(чисто);
  if (v && typeof v === 'object') {
    return Object.fromEntries(
      Object.entries(v).filter(([, x]) => x !== undefined).map(([k, x]) => [k, чисто(x)]),
    );
  }
  return v;
}

/** Успех: данные, потом подсказки. Подсказок может не быть — тогда строки нет. */
export function ok(data, help = []) {
  const тело = { ...data };
  if (help.length) тело.help = help;
  console.log(toon(чисто(тело)));
}

/**
 * Отказ. `error` — короткая причина машинным словом, `text` — человеческая фраза;
 * агенту нужно первое, чтобы ветвиться, и второе, чтобы передать человеку.
 */
export function fail(error, text, { help = [], code = КОД.fail, ...extra } = {}) {
  console.log(toon(чисто({ ok: false, error, text, ...extra, ...(help.length ? { help } : {}) })));
  process.exitCode = code;
}

/** Неверный вызов: не тот флаг, не то число аргументов, неизвестная команда. */
export function usage(text, help = []) {
  fail('usage', text, { help, code: КОД.usage });
}
