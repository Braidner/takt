/**
 * TOON — формат вывода команд Takt.
 *
 * Команды разговаривают не с человеком, а с агентом, и платит за этот разговор
 * человек — токенами. JSON тратит их на скобки и на повтор имён полей в каждой
 * записи: у раскадровки из сорока планов имя `seconds` печатается сорок раз.
 * TOON называет поля один раз заголовком таблицы, как CSV, но остаётся
 * самоописывающим: видно, сколько записей и какие у них поля.
 *
 * Кодировщик свой, а не библиотека. У проекта одна зависимость — playwright, —
 * и заводить вторую ради формата, который умещается в полсотни строк, не за что.
 * Покрыты те формы, что реально выходят из наших команд: плоский объект,
 * однородный список записей, список строк, вложенный объект. Разнородный список
 * не притворяется таблицей: заголовок соврал бы про строки, где поля нет.
 *
 * Без импортов Node: модуль грузят и команды, и node:test.
 */

/** Значение, которое можно положить в строку таблицы без потери смысла. */
const скаляр = (v) => v === null || ['string', 'number', 'boolean'].includes(typeof v);

/**
 * Кавычки ставятся не для красоты: без них запятая внутри значения превратилась бы
 * в разделитель колонок, а перевод строки — в новую запись.
 */
function значение(v) {
  if (v === null) return 'null';
  if (typeof v !== 'string') return String(v);
  // Двоеточие опаснее прочего: без кавычек «собрать: takt build» читается как
  // вложенный ключ со значением, а не как одна подсказка.
  const опасно = /[",:\n\r]/.test(v) || v.trim() !== v || v === '';
  if (!опасно) return v;
  return `"${v.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\r/g, '\\r')}"`;
}

/** Однородный список записей — тот, где у всех одни и те же поля со скалярами. */
function таблица(list) {
  if (!list.length) return null;
  const поля = Object.keys(list[0]);
  if (!поля.length) return null;
  for (const item of list) {
    if (!item || typeof item !== 'object' || Array.isArray(item)) return null;
    const свои = Object.keys(item);
    if (свои.length !== поля.length || свои.some((k, i) => k !== поля[i])) return null;
    if (поля.some((k) => !скаляр(item[k]))) return null;
  }
  return поля;
}

function строки(key, v, отступ) {
  const пробелы = '  '.repeat(отступ);
  if (Array.isArray(v)) {
    if (!v.length) return [`${пробелы}${key}[0]:`];
    if (v.every(скаляр)) {
      return [`${пробелы}${key}[${v.length}]: ${v.map(значение).join(',')}`];
    }
    const поля = таблица(v);
    if (поля) {
      return [
        `${пробелы}${key}[${v.length}]{${поля.join(',')}}:`,
        ...v.map((item) => `${пробелы}  ${поля.map((k) => значение(item[k])).join(',')}`),
      ];
    }
    // Разнородное: каждая запись сама за себя, как в списке YAML.
    const out = [`${пробелы}${key}[${v.length}]:`];
    for (const item of v) {
      const свои = вложенное(item, отступ + 1);
      out.push(`${пробелы}  - ${свои[0].trimStart()}`, ...свои.slice(1));
    }
    return out;
  }
  if (v && typeof v === 'object') {
    return [`${пробелы}${key}:`, ...вложенное(v, отступ + 1)];
  }
  return [`${пробелы}${key}: ${значение(v)}`];
}

function вложенное(obj, отступ) {
  const out = [];
  for (const [k, v] of Object.entries(obj)) {
    if (v === undefined) continue;
    out.push(...строки(k, v, отступ));
  }
  return out;
}

/** Объект в TOON. Поля со значением `undefined` не печатаются: их нет. */
export function toon(obj) {
  return вложенное(obj || {}, 0).join('\n');
}
