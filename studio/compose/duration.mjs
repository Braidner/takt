/**
 * Длительность плана выводится, а не назначается.
 *
 * Разбор старого ролика показал общую причину брака: на 52 секунды приходилось три
 * действия и семь титров, а длительность каждой сцены человек ставил числом 6–8.
 * Камере было нечего показывать в четырёх сценах из семи — и это видно.
 *
 * Поэтому время плана считается из его содержания: сколько камера подъезжает, сколько
 * длится само действие и сколько зритель смотрит на результат. Человек по-прежнему
 * может назначить своё — но тогда это его решение, помеченное как ручное, а не
 * умолчание, которое никто не выбирал.
 *
 * Без импортов Node: модуль грузит и браузер, и node:test.
 */

/**
 * Подводка камеры. В спеке — «0,6 с, если камера двигается, иначе 0»; у нас она
 * двигается всегда: план без якоря и без длинной страницы получает дрейф, потому что
 * неподвижный кадр в ролике читается как стоп-кадр. Условие выродилось в константу.
 */
export const LEAD_IN = 0.6;
/** Удержание результата: действие без паузы после него зритель не успевает прочитать. */
export const HOLD_OUT = 2.6;
/** Знаков в секунду при наборе: быстрее выглядит как вставка из буфера. */
export const TYPE_RATE = 12;
/** Скорость прокрутки по умолчанию, px/с — та же, что у съёмки. */
export const SCROLL_SPEED = 600;
/** Короче не успевает прочитаться, длиннее тормозит ролик. Границы эталона. */
export const MIN = 3.5;
export const MAX = 9;

/**
 * Заставка и финальная плашка. Живут здесь, рядом с прочими длительностями, а не в
 * композиции: время ролика должно считаться в одном месте. Пока эти две константы
 * знала только композиция, раскадровка считала таймкоды без них — и всё, что
 * привязано ко времени (клипы дорожек, замечания, реплики), стояло на 2,6 с раньше
 * картинки.
 */
/**
 * Доля ширины кадра под окно приложения.
 *
 * Живёт здесь же, рядом с прочими решениями о том, как выглядит ролик. Восемь
 * десятых — компромисс: интерфейс крупный, но окно остаётся окном, вокруг него
 * видно кадр, а не только рамку.
 */
export const SCREEN_SIZE = 0.8;

export const SLATE = 2.6;
export const END = 2.2;

const round = (s) => Math.round(s * 10) / 10;

/** Сколько длится само действие. Закрытый список: неизвестное считаем мгновенным. */
function actSeconds(action) {
  if (!action) return 0;
  switch (action.kind) {
    case 'click':  return 0.2;
    case 'type':   return (action.text || '').length / TYPE_RATE;
    case 'scroll': return Math.abs(action.distance || 0) / (action.speed || SCROLL_SPEED);
    case 'hold':   return Number(action.seconds) || 0;
    // Переход не попадает в кадр вовсе: съёмка начинается после того, как экран готов.
    case 'goto':   return 0;
    default:       return 0;
  }
}

/**
 * Вставка держится дольше обычного плана: на ней не смотрят на действие, а читают.
 * Схему из трёх блоков глазами проходят секунд за пять — короче человек успевает
 * только заметить, что что-то мелькнуло.
 */
export const INSERT = 5.5;

export function planDuration(plan, state = null) {
  /* Снятое движение нельзя ни растянуть, ни обрезать: длину живого плана задаёт
     запись, и она главнее назначенного человеком. Иначе раскадровка считает одно,
     плёнка — другое, и всё, что идёт следом, разъезжается с картинкой. */
  if (plan?.mode === 'live') {
    const снято = Math.round((state?.seconds || 0) * 10) / 10;
    if (снято > 0.4) return { seconds: снято, source: 'shot', over: false };
  }
  if (plan?.duration?.source === 'manual') {
    return { seconds: plan.duration.seconds, source: 'manual', over: false };
  }
  if (plan?.mode === 'insert') return { seconds: INSERT, source: 'derived', over: false };
  const raw = LEAD_IN + actSeconds(plan?.action) + HOLD_OUT;
  return {
    seconds: round(Math.min(MAX, Math.max(MIN, raw))),
    source: 'derived',
    // Превышение не выправляется молча: длинный план надо разбить надвое, и это
    // работа режиссёра. Скрыть её растяжкой границы значит потерять её навсегда.
    over: raw > MAX,
  };
}
