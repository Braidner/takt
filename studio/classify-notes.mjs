/**
 * Разбор замечаний по стоимости исполнения.
 *
 * Стоимость правок различается на порядок, и человек этого не видит: «поправь титр» и
 * «покажи другой раздел» выглядят одинаково — две строчки текста. Первое стоит минуту
 * пересборки, второе требует новой съёмки и двадцати минут. Поэтому агент отвечает
 * планом с оценкой ДО работы, а не ставит человека перед фактом получасового ожидания.
 *
 * Классификация грубая намеренно: точный разбор смысла — работа модели, а этому модулю
 * достаточно отделить дешёвое от дорогого и не соврать в сторону «дёшево». Спорные
 * случаи уходят в «непонятно» и выносятся на уточнение, а не втихую в дешёвую корзину.
 *
 * Ищем по корням без границ слова: \b в JavaScript определяется по латинице, и на
 * русском тексте не срабатывает вовсе — правило с \b молча не находит ничего.
 */

/**
 * Что относится к какому виду работы. Порядок проверки важен, и он не произвольный.
 *
 * Слово «показать» встречается и в дорогом «покажи вместо этого раздел настроек», и в
 * дешёвом «здесь показать схему». Одним правилом их не различить, поэтому признаки
 * пересъёмки разделены: однозначные идут первыми, а слабое «показать» — последним,
 * уже после того, как схемы, озвучка и монтаж разобрали своё.
 */
const RULES = [
  {
    kind: 'shoot',
    // Однозначные: эти слова означают другое действие в кадре и ничем иным не лечатся.
    test: /(вместо этого|другой раздел|другую страниц|открой|открыть|зайти|перейти|нажм|кликн|введи|заполни|создай|удали|выбери)/i,
    title: 'Пересъёмка',
    why: 'меняется то, что происходит в кадре',
    minutes: 20,
  },
  {
    kind: 'voice',
    test: /(озвуч|голос|диктор|произнос|ударени|интонац|реплик)/i,
    title: 'Озвучка',
    why: 'пересинтез затронутых реплик, остальные не трогаем',
    minutes: 3,
  },
  {
    kind: 'diagram',
    test: /(схем|диаграмм|врезк)/i,
    title: 'Врезка-схема',
    why: 'собрать схему и пересобрать ролик',
    minutes: 5,
  },
  {
    kind: 'edit',
    test: /(титр|подпис|пауз|подрез|обрез|ускор|замедл|длиннее|короче|камер|наезд|зум|переход)/i,
    title: 'Монтаж',
    why: 'пересборка ролика без новой съёмки',
    minutes: 2,
  },
  {
    kind: 'shoot',
    // Слабый признак: сюда доходит только то, что не разобрали правила выше.
    test: /(показ|покаж)/i,
    title: 'Пересъёмка',
    why: 'меняется то, что происходит в кадре',
    minutes: 20,
  },
];

/**
 * Замечание с адресом — вход перегенерации: режиссёр перечитывает его вместе с
 * сюжетом и выдаёт новую раскадровку. Съёмка при этом не нужна, поэтому и минут
 * втрое меньше пересборки с новым прогоном.
 */
const DIRECTED = {
  kind: 'direct',
  title: 'Перегенерация',
  why: 'режиссёр пересоберёт раскадровку с учётом замечания',
  minutes: 3,
};

const FALLBACK = {
  kind: 'unclear',
  title: 'Непонятно',
  why: 'формулировка не даёт понять, что менять — уточнить у автора',
  minutes: null,
};

/**
 * Вид работы по замечанию.
 *
 * Принимает и строку, и само замечание с адресом. Адрес важнее слов: «слишком долго
 * висит пустой экран» не содержит ни одного признака из правил, и без адреса такое
 * замечание уходило в «непонятно» — а с адресом это внятная работа режиссёра над
 * конкретным планом. Просьбу переснять адрес не перебивает: раскадровкой не добудешь
 * состояние, которого не снимали.
 */
export function classifyNote(note) {
  const t = String(typeof note === 'string' ? note : note?.text || '');
  for (const rule of RULES) {
    if (rule.test.test(t)) {
      const { test, ...rest } = rule;
      return rest;
    }
  }
  if (typeof note === 'object' && (note?.plan || note?.effect)) return DIRECTED;
  return FALLBACK;
}

/**
 * План работ по пачке замечаний.
 *
 * Оценка суммируется не «в лоб»: пересъёмка нужна одна на все замечания, требующие
 * съёмки, а не по одной на каждое. То же с пересборкой ролика — она общая.
 */
export function planFor(notes) {
  const open = notes.filter((n) => n.status !== 'applied');
  const items = open.map((n) => ({ ...n, ...classifyNote(n) }));

  const kinds = new Set(items.map((i) => i.kind));
  let minutes = 0;
  if (kinds.has('shoot')) minutes += 20;          // один прогон покрывает все такие правки
  if (kinds.has('voice')) minutes += 3;
  if (kinds.has('diagram')) minutes += 5;
  // Перегенерация одна на все адресные замечания: режиссёр читает их разом.
  if (kinds.has('direct')) minutes += 3;
  // Пересборка нужна в любом случае, кроме чистой пересъёмки — там она уже входит в срок.
  if (kinds.has('edit') || (kinds.size && !kinds.has('shoot') && !kinds.has('direct'))) minutes += 2;

  return {
    items,
    minutes,
    needsShooting: kinds.has('shoot'),
    unclear: items.filter((i) => i.kind === 'unclear'),
  };
}

