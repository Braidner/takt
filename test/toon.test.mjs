/**
 * TOON — формат вывода команд.
 *
 * Кодирует библиотека @toon-format/toon, а тест держит контракт: перечислены те
 * формы, что реально выходят из команд Takt, и то, как они обязаны выглядеть.
 * Смена мажорной версии библиотеки может тихо поменять вывод — тогда упадёт этот
 * тест, а не разбор ответа на стороне агента, где о причине уже не догадаться.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { encode as toon } from '@toon-format/toon';

test('плоский объект: ключ и значение через двоеточие', () => {
  assert.equal(toon({ ok: true, out: 'movie.mp4', fps: 30 }),
               'ok: true\nout: movie.mp4\nfps: 30');
});

test('однородный список записей становится таблицей с заголовком', () => {
  // Ради этого формат и затевался: имена полей называются один раз, а не в каждой строке.
  const плёнка = toon({
    plans: [
      { n: 1, id: 'p01', seconds: 8.2 },
      { n: 2, id: 'p02', seconds: 7.7 },
    ],
  });
  assert.equal(плёнка, 'plans[2]{n,id,seconds}:\n  1,p01,8.2\n  2,p02,7.7');
});

test('список строк идёт одной строкой с длиной', () => {
  assert.equal(toon({ help: ['собрать: takt build', 'показать: takt poll'] }),
               'help[2]: "собрать: takt build","показать: takt poll"');
});

test('пустой список говорит о себе, а не молчит', () => {
  // Пустое состояние обязано быть видимым: молчание агент читает как «поле забыли».
  assert.equal(toon({ issues: [] }), 'issues: []');
});

test('запятая и кавычки в значении не рвут таблицу', () => {
  const строки = toon({ notes: [{ id: 'n1', text: 'долго висит, потом рывок' }] });
  assert.equal(строки, 'notes[1]{id,text}:\n  n1,"долго висит, потом рывок"');
  assert.match(toon({ title: 'Ролик "Медиа"' }), /^title: "Ролик \\"Медиа\\""$/);
});

test('перевод строки внутри значения экранируется, а не ломает строку', () => {
  assert.equal(toon({ error: 'не нашёл кнопку\nпопробуйте разведку' }),
               'error: "не нашёл кнопку\\nпопробуйте разведку"');
});

test('разнородный список не притворяется таблицей', () => {
  // Записи с разным набором полей в таблицу не ложатся: заголовок соврал бы про
  // те строки, где поля нет вовсе.
  const из = toon({ items: [{ a: 1 }, { b: 2 }] });
  assert.equal(из, 'items[2]:\n  - a: 1\n  - b: 2');
});

test('вложенный объект уходит с отступом', () => {
  assert.equal(toon({ duration: { seconds: 8.2, source: 'derived' } }),
               'duration:\n  seconds: 8.2\n  source: derived');
});

test('null остаётся null: пустое значение — это значение', () => {
  assert.equal(toon({ url: null, n: 0 }), 'url: null\nn: 0');
});
